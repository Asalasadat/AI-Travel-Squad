class PlaceModel {
  final String name;
  final String city;
  final String type;
  final String description;
  final String image;
  final double score;

  final double latitude;
  final double longitude;

  PlaceModel({
    required this.name,
    required this.city,
    required this.type,
    required this.description,
    required this.image,
    required this.score,
    required this.latitude,
    required this.longitude,
  });
}

